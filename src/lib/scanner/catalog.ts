export type FindingKey = keyof typeof FINDING_CATALOG;

export function makeFinding(
  key: FindingKey,
  observation: string,
  evidence: Record<string, unknown> = {},
  overrides: Partial<Pick<Finding, "severity" | "confidence">> = {},
): Finding {
  const entry = FINDING_CATALOG[key] as CatalogEntry;
  return {
    key,
    checkKey: entry.checkKey,
    category: entry.category,
    title: entry.title,
    observation,
    severity: overrides.severity ?? entry.severity,
    explanation: entry.explanation,
    impact: entry.impact,
    remediation: entry.remediation,
    evidence,
    confidence: overrides.confidence ?? entry.confidence,
    limitation: entry.limitation,
  };
}
